const CELL = 16, DOT = 13, COLS = 22, ROWS = 12;
// 표정 가운데를 기존 얼굴 기준점(512, 450)에 맞춘다
const X0 = 512 - (COLS * CELL) / 2, Y0 = 450 - (ROWS * CELL) / 2;
const COLOR = { "#": "#FFFFFF", "+": "#7A7A7A", o: "#3C3C3C", b: "#57B8F5" };
const OFF = "#1E1E1E";

function dotSvg(rows) {
  const dot = (x, y, fill) => `<rect x="${x}" y="${y}" width="${DOT}" height="${DOT}" rx="2" fill="${fill}"/>`;
  let out = "";
  // 꺼진 점은 앞유리 전체에 깐다 (전광판 느낌). 표정 칸 바깥까지 같은 간격
  for (let y = Y0 - CELL * 27; y < 1024; y += CELL) for (let x = X0 - CELL * 15; x < 1024; x += CELL) out += dot(x, y, OFF);
  // 앞유리 UV는 앞에서 볼 때 좌우가 뒤집혀 있어서, 글자 그림과 같게 보이도록 칸을 거꾸로 놓는다
  rows.forEach((row, r) => [...row].reverse().forEach((ch, c) => { if (COLOR[ch]) out += dot(X0 + c * CELL, Y0 + r * CELL, COLOR[ch]); }));
  return `<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024">${out}</svg>`;
}

for (const [name, rows] of Object.entries(faces)) {
  if (rows.length !== ROWS || rows.some((r) => r.length !== COLS)) throw new Error("격자 크기가 틀림: " + name);
}

module.exports = { dotFaces: Object.fromEntries(Object.entries(faces).map(([k, v]) => [k, dotSvg(v)])) };
