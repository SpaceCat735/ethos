def shape_profile(body):
    # SHAPE_SPECS(m 단위)를 car.py가 쓰는 정규화 프로파일로 바꾼다. 없으면 None (차급 공용 BLADE_PROFILES를 쓴다)
    s = SHAPE_SPECS.get(body)
    if not s: return None
    L, W, H = BODIES[body][:3]
    t = lambda x: 1.0 - 2.0 * x / L
    hv = lambda pts: [(round(t(x), 4), round(h / H, 4)) for x, h in pts]
    return dict(top=hv(s["top"]), belt=hv(s["belt"]), floor=hv(s["floor"]), wbelt=s["wbelt"], wtop=[(t_, min(v * s.get("tumble", 1.12), .97)) for t_, v in s["wtop"]],   # 텀블홈: 유리 윗폭 배율 (세단 약 10°, SUV 약 5°, 경차 거의 수직)
                cowl=t(s["cowl"]), wsend=t(s["ws"]), gend=t(s["gend"]), spoiler=s["spoiler"],
                wheel_tf=t(s["foh"]), wheel_tr=-t(L - s["roh"]), wheel_t=t(s["foh"]),
                nose=s.get("nose", (0, 0, 0)), tail=s.get("tail", (0, 0)))
